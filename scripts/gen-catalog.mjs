// Writes docs/actions-data.js, the data of the action catalog (docs/index.html),
// from the built-in definitions in hooks/actions.ts (through buildCatalog in
// hooks/catalog.ts). Run it after adding or changing a built-in action:
//
//   node scripts/gen-catalog.mjs
//
// tests/catalog.test.ts fails while the file written here and the definitions
// differ. Needs Node 24 or later: it imports the TypeScript sources as they are
// (type stripping) and resolves their extensionless imports with
// module.registerHooks.

import { writeFileSync } from 'node:fs'
import * as nodeModule from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const MIN_NODE_MAJOR = 24
const major = Number(process.versions.node.split('.')[0])
if (!(major >= MIN_NODE_MAJOR) || typeof nodeModule.registerHooks !== 'function') {
  console.error(
    `gen-catalog: Node ${MIN_NODE_MAJOR} or later is needed (this is ${process.version}); ` +
      `it imports hooks/*.ts as they are. With asdf, for one: ASDF_NODEJS_VERSION=24.21.0 node scripts/gen-catalog.mjs`,
  )
  process.exit(1)
}

// The hooks import each other without an extension ('./actions'): try .ts, then .tsx.
nodeModule.registerHooks({
  resolve(specifier, context, nextResolve) {
    if ((specifier.startsWith('./') || specifier.startsWith('../')) && !/\.[cm]?[jt]sx?$/.test(specifier)) {
      for (const ext of ['.ts', '.tsx']) {
        try {
          return nextResolve(specifier + ext, context)
        } catch {
          // Not this one: try the next extension.
        }
      }
    }
    return nextResolve(specifier, context)
  },
})

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { buildCatalog } = await import(pathToFileURL(join(root, 'hooks', 'catalog.ts')).href)
const catalog = buildCatalog()

const out = join(root, 'docs', 'actions-data.js')
const text = [
  '// Generated by scripts/gen-catalog.mjs from hooks/actions.ts: do not edit by hand.',
  '// Regenerate after changing the built-in actions: node scripts/gen-catalog.mjs (Node 24 or later).',
  '// tests/catalog.test.ts fails while this file and the definitions differ.',
  `globalThis.QUICK_ACTIONS_CATALOG = ${JSON.stringify(catalog, null, 2)};`,
  '',
].join('\n')
writeFileSync(out, text)
console.log(`gen-catalog: wrote ${catalog.total} actions in ${catalog.categories.length} categories to docs/actions-data.js`)
